import java.util.Scanner;
class AssignmentOperator
{
	public static void main(String args[])
	{
		Scanner sc=new Scanner(System.in);
		System.out.print("Enter Number");
		int a = sc.nextInt();
		System.out.println(a);
	   a+=5; 
	   System.out.println(a);
	   a-=5;
	   System.out.println(a);
	   a*=5;
	   System.out.println(a);
	}
}
	   
	